import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,existsSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {sourceIneligibility,referenceFailure,mutantDisposition} from './v3-screen-go.mjs';
assert.equal(sourceIneligibility('.gen/go/x.go'),'generated-or-vendored-target');
assert.equal(sourceIneligibility('vendor/a/x.go'),'generated-or-vendored-target');
assert.equal(sourceIneligibility('x.go','// Code generated by tool. DO NOT EDIT.\npackage p'),'generated-or-vendored-target');
assert.equal(sourceIneligibility('x.go','package p'),null);
assert.equal(referenceFailure({category:'build-failure',stages:[{stderr:'cannot find package "example.org/dep"'}]}),'incomplete-missing-dependency');
assert.equal(referenceFailure({category:'test-failure',stages:[{stderr:'assertion failed'}]}),'reference-behavioral-failure');
const d=mkdtempSync(join(tmpdir(),'go-no-tests-'));
try{
 writeFileSync(join(d,'x.go'),'package p\nfunc X() int { return 1 }\n');
 const r=spawnSync('go',['test','-c','-o',join(d,'h0.test')],{cwd:d,env:{PATH:process.env.PATH,HOME:d,GO111MODULE:'off',GOTOOLCHAIN:'local',GOPROXY:'off'},encoding:'utf8',timeout:60000});
 assert.equal(r.status,0);assert(!existsSync(join(d,'h0.test')));
 assert.equal(referenceFailure({category:'test-failure',stages:[r]}),'ineligible-no-executable-tests');
}finally{rmSync(d,{recursive:true,force:true});}
console.log('Real no-test package, generated/vendor exclusion, and reference classification passed');

assert.equal(mutantDisposition({category:'test-failure'}),'rejected');
for(const ev of [{category:'environment-error'}, {category:'test-failure',reason:'test-timeout'}, {category:'test-failure',reason:'test-completion-contract'}, {category:'build-failure',stages:[{stderr:'cannot find package "x"'}]}])assert.equal(mutantDisposition(ev),'incomplete');
assert.equal(mutantDisposition({category:'build-failure',stages:[{stderr:'syntax error'}]}),'not-rejected');
